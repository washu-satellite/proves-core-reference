"""Tests for ``scripts/make_bench_sequence.py``, claiming BENCH-1..2.

Each test asserts one clause of its row's pass criteria
(``docs-site/requirements/bench.md``) from the command line, using the flags and
exit codes of ``docs-site/dev-loop/cycles/cycle-k-plan.md`` section 1.1, the
generation rule of section 1.2 and the header of section 1.3. One test per
fixture row of section 1.4. Every line of generated text is proven on a small
source written into ``tmp_path``; the tree is never edited. On the real tree a
test asserts only the exit code of ``--check`` (cycle-k-review amendment 1).

Fixture sources are assembled from verbatim lines of ``sequences/startup.seq``
(named below by their line number in that file) and written byte for byte, one
``\\n`` after each line.
"""

import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SCRIPT = Path("scripts") / "make_bench_sequence.py"

#: The first two lines of every output (section 1.3), each ending in ``\n``.
#: ASCII hyphen after "startup.seq", not an em dash.
HEADER = (
    "; GENERATED by scripts/make_bench_sequence.py from sequences/startup.seq"
    " - do not edit; regenerate: make bench-sequence\n"
    "; Bench variant: no antennaDeployer.DEPLOY, no lora.TRANSMIT ENABLED,"
    " no modeManager.EXIT_SAFE_MODE, no detumbleManager.SET_MODE."
    " Select it with startupManager.STARTUP_SEQUENCE_FILE.\n"
)

# Verbatim lines of sequences/startup.seq, keyed by line number.
LINE_1 = (
    "R00:00:10 CdhCore.events.SET_ID_FILTER, 570462208, ENABLED"
    " ; LORA APID unexpected sequence count"
)
LINE_7 = "R00:45:00 ReferenceDeployment.antennaDeployer.DEPLOY"
LINE_8 = "R00:00:00 ReferenceDeployment.lora.TRANSMIT, DISABLED"
LINE_17 = "R00:00:00 ReferenceDeployment.lora.TRANSMIT ENABLED"
LINE_19 = "; Exit Safe Mode should turn on faces"
LINE_20 = "R00:00:00 ReferenceDeployment.modeManager.EXIT_SAFE_MODE"
LINE_22 = "R00:05:00 ReferenceDeployment.detumbleManager.SET_MODE, AUTO"
LINE_23 = "R03:00:00 ReferenceDeployment.detumbleManager.SET_MODE, DISABLED"

#: ``error: <what> (<path>)`` (section 1.1, exit 2).
ERROR_LINE_RE = re.compile(r"^error: .+ \((?P<path>.+)\)$")


@dataclass(frozen=True)
class Run:
    """One invocation of the script."""

    returncode: int
    stdout: str
    stderr: str


def run(
    source: Path | None = None,
    output: Path | None = None,
    mode: str | None = None,
) -> Run:
    """Run the script from the repo root.

    ``--source``/``--output`` are passed only when given; ``mode`` is
    ``"--stdout"``, ``"--check"`` or ``None`` (default mode: write ``--output``).
    """
    cmd = [sys.executable, str(SCRIPT)]
    if source is not None:
        cmd += ["--source", str(source)]
    if output is not None:
        cmd += ["--output", str(output)]
    if mode is not None:
        cmd.append(mode)
    proc = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True, timeout=60)
    return Run(proc.returncode, proc.stdout, proc.stderr)


def text(*lines: str) -> str:
    """The file text of ``lines``: each line followed by one ``\\n``."""
    return "".join(line + "\n" for line in lines)


def source_file(tmp_path: Path, *lines: str, name: str = "startup.seq") -> Path:
    """Write ``lines`` byte for byte to ``tmp_path/src/<name>`` and return it."""
    path = tmp_path / "src" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text(*lines).encode("ascii"))
    return path


def output_path(tmp_path: Path, sub: str = "out") -> Path:
    """A not-yet-existing ``bench_startup.seq`` under ``tmp_path/<sub>``."""
    path = tmp_path / sub / "bench_startup.seq"
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def generated(tmp_path: Path, *lines: str, sub: str = "out") -> str:
    """Run ``--stdout`` on a source holding ``lines``; return stdout, asserting exit 0."""
    r = run(
        source_file(tmp_path, *lines, name=f"{sub}.seq"),
        output_path(tmp_path, sub),
        "--stdout",
    )
    assert r.returncode == 0, f"exit {r.returncode}; stderr:\n{r.stderr}"
    return r.stdout


