@pytest.mark.verifies("BENCH-1")
def test_bench1_drops_hazard_commands(tmp_path):
    """Output = the two fixed header lines then every source line byte for byte except
    command lines for antennaDeployer.DEPLOY, modeManager.EXIT_SAFE_MODE,
    detumbleManager.SET_MODE (any argument) and lora.TRANSMIT with first argument ENABLED.
    """
    out = generated(tmp_path, LINE_1, LINE_7, LINE_8, LINE_17, LINE_20, LINE_22)
    assert out == HEADER + text(LINE_1, LINE_8)


@pytest.mark.verifies("BENCH-1")
def test_bench1_transmit_disabled_kept(tmp_path):
    """TRANSMIT, DISABLED [is] kept."""
    assert generated(tmp_path, LINE_8) == HEADER + text(LINE_8)


@pytest.mark.verifies("BENCH-1")
def test_bench1_transmit_enabled_without_comma_dropped(tmp_path):
    """[Command lines for] lora.TRANSMIT with first argument ENABLED [are dropped]
    (no-comma form, startup.seq line 17)."""
    assert generated(tmp_path, LINE_17) == HEADER


@pytest.mark.verifies("BENCH-1")
def test_bench1_comment_before_dropped_line_dropped(tmp_path):
    """[Except] a comment line immediately before a dropped line."""
    before_dropped = generated(tmp_path, "; note", LINE_20, sub="dropped")
    assert before_dropped == HEADER

    before_kept = generated(tmp_path, "; note", LINE_8, sub="kept")
    assert before_kept == HEADER + text("; note", LINE_8)


@pytest.mark.verifies("BENCH-1")
def test_bench1_blank_lines_kept(tmp_path):
    """Blank lines are kept."""
    assert generated(tmp_path, LINE_1, "", LINE_8) == HEADER + text(LINE_1, "", LINE_8)


@pytest.mark.verifies("BENCH-1")
def test_bench1_trailing_blank_lines_dropped(tmp_path):
    """Blank lines inside the sequence are kept; blank lines at the end of the output
    (every blank line after the last non-blank line) are dropped, so the file ends in
    exactly one \\n.
    """
    out = generated(tmp_path, LINE_1, "", LINE_8, "", "", "")
    assert out == HEADER + text(LINE_1, "", LINE_8)
    assert out.endswith("\n") and not out.endswith("\n\n")


@pytest.mark.verifies("BENCH-1")
def test_bench1_stdout_prints_same_text_writes_nothing(tmp_path):
    """--stdout prints the same text and writes nothing."""
    src = source_file(
        tmp_path,
        LINE_1,
        "",
        LINE_7,
        LINE_8,
        LINE_17,
        "",
        LINE_19,
        LINE_20,
        LINE_22,
        LINE_23,
    )
    out = output_path(tmp_path)

    printed = run(src, out, "--stdout")
    assert printed.returncode == 0, f"stderr:\n{printed.stderr}"
    assert not out.exists(), "--stdout wrote --output"
    assert list(out.parent.iterdir()) == [], "--stdout wrote into the output directory"

    written = run(src, out)
    assert written.returncode == 0, f"stderr:\n{written.stderr}"
    assert out.exists(), "default mode did not write --output"
    file_text = out.read_bytes().decode("ascii")
    assert file_text.startswith(HEADER)
    assert printed.stdout == file_text


@pytest.mark.verifies("BENCH-1")
def test_bench1_missing_source_exits_2(tmp_path):
    """A missing --source exits 2 with one stderr line."""
    missing = tmp_path / "src" / "no_such_startup.seq"
    for mode in (None, "--stdout", "--check"):
        out = output_path(tmp_path, sub=f"out{mode or ''}")
        r = run(missing, out, mode)
        assert r.returncode == 2, f"mode {mode}: exit {r.returncode}"
        assert r.stdout == "", f"mode {mode}: stdout {r.stdout!r}"
        err = r.stderr.splitlines()
        assert len(err) == 1, f"mode {mode}: stderr {r.stderr!r}"
        m = ERROR_LINE_RE.match(err[0])
        assert m, f"mode {mode}: not an error: <what> (<path>) line: {err[0]!r}"
        assert missing.name in m.group("path")
        assert not out.exists(), f"mode {mode}: wrote --output"


