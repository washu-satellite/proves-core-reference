@pytest.mark.verifies("BENCH-2")
def test_bench2_check_equal_stale_missing(tmp_path):
    """With --check: exit 0 when --output equals the generated text byte for byte; exit 1
    with the line bench_startup.seq: stale after any byte differs; exit 1 with
    bench_startup.seq: missing when absent; nothing is written in --check mode.
    """
    src = source_file(tmp_path, LINE_1, "", LINE_7, LINE_8, LINE_19, LINE_20)
    out = output_path(tmp_path)

    written = run(src, out)
    assert written.returncode == 0, f"stderr:\n{written.stderr}"
    assert out.exists(), "default mode did not write --output"

    equal = run(src, out, "--check")
    assert equal.returncode == 0, f"stdout:\n{equal.stdout}\nstderr:\n{equal.stderr}"

    stale_bytes = out.read_bytes() + b"x"
    out.write_bytes(stale_bytes)
    stale = run(src, out, "--check")
    assert stale.returncode == 1
    assert stale.stdout == "bench_startup.seq: stale\n"
    assert out.read_bytes() == stale_bytes, "--check rewrote a stale --output"

    out.unlink()
    missing = run(src, out, "--check")
    assert missing.returncode == 1
    assert missing.stdout == "bench_startup.seq: missing\n"
    assert not out.exists(), "--check wrote a missing --output"


@pytest.mark.verifies("BENCH-2")
def test_bench2_current_tree_check_exits_0():
    """On the current tree --check exits 0."""
    r = run(mode="--check")
    assert r.returncode == 0, f"stdout:\n{r.stdout}\nstderr:\n{r.stderr}"
